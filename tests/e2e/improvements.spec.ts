  expect(csv).toContain('"2026-06-10","Certified seed","Seeds","Cash","8000"')
  await page.emulateMedia({ media: 'print' })
  await expect(identity).toBeVisible()
  await expect(page.getByRole('button', { name: 'Export CSV', exact: true })).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Edit actual harvest', exact: true })).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Download backup', exact: true })).not.toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Main navigation', exact: true })).not.toBeVisible()
  await expect(page.locator('.report-ledger').first().locator('thead')).toHaveCSS('display', 'table-header-group')
  await expect(page.locator('.report-ledger').nth(1)).toContainText('Illustrative sample entry, not a verified farm record.')
  await page.pdf({ path: info.outputPath('sample-season-report.pdf'), format: 'A4', printBackground: true })
