test('switching seasons asks before discarding a scenario and keeps the original selection on cancellation', async ({ page }) => {
  await sample(page)
  const selector = page.getByLabel('Active season', { exact: true })
  const sampleId = await selector.inputValue()
  await page.getByRole('button', { name: 'New season', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'Start a new season', exact: true })
  await form.getByLabel('Farm nickname', { exact: true }).fill('Scenario continuity farm')
  await form.getByLabel('Season name', { exact: true }).fill('Other season')
  await form.getByRole('button', { name: 'Save season', exact: true }).click()
  await expect(form).toHaveCount(0)
  const otherId = await selector.inputValue()
  expect(otherId).not.toBe(sampleId)
  await selector.selectOption(sampleId)
  await nav(page, 'Scenarios')
  await page.getByLabel('Scenario name', { exact: true }).fill('Stay on my sample')
  await selector.selectOption(otherId)
  await discardDialog(page).getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(selector).toHaveValue(sampleId)
  await expect(page.getByLabel('Scenario name', { exact: true })).toHaveValue('Stay on my sample')
  await selector.selectOption(otherId)
  await discardDialog(page).getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(selector).toHaveValue(otherId)
  await expect(page.getByLabel('Scenario name', { exact: true })).toHaveValue('Higher input costs')
  await page.getByLabel('Scenario name', { exact: true }).fill('Other season unsaved')
  await selector.selectOption(sampleId)
  await expect(discardDialog(page)).toBeVisible()
  await discardDialog(page).getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(selector).toHaveValue(sampleId)
})

