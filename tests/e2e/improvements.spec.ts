import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function sample(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Explore a sample farm', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Every season, a clearer plan.' })).toBeVisible()
  await page.getByRole('button', { name: 'Dismiss', exact: true }).click()
}

async function nav(page: Page, name: string, language: 'en' | 'fil' = 'en') {
  const mobile = (page.viewportSize()?.width ?? 1440) <= 800
  const navigation = language === 'fil'
    ? (mobile ? 'Nabigasyon sa mobile' : 'Pangunahing nabigasyon')
    : (mobile ? 'Mobile navigation' : 'Main navigation')
  await page.getByRole('navigation', { name: navigation, exact: true }).getByRole('link', { name, exact: true }).click()
}

function discardDialog(page: Page) {
  return page.getByRole('dialog', { name: 'Discard unsaved changes?', exact: true })
}

test('Overview opens an expense form immediately and saves into the expense log', async ({ page }) => {
  await sample(page)
  await page.getByRole('button', { name: 'Add expense', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'Add expense', exact: true })
  await expect(form).toBeVisible()
  await expect(page).toHaveURL(/#expenses$/)
  await form.getByLabel('Expense name', { exact: true }).fill('Quick entry transport')
  await form.getByLabel('Amount paid or valued (₱)', { exact: false }).fill('125.50')
  await form.getByRole('button', { name: 'Save expense', exact: true }).click()
  await expect(form).toHaveCount(0)
  await expect(page.getByRole('row').filter({ hasText: 'Quick entry transport' })).toContainText('₱125.50')
  await page.reload()
  await expect(page.getByRole('row').filter({ hasText: 'Quick entry transport' })).toContainText('₱125.50')
})

