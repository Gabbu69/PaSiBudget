test('dirty expense dismissal keeps inputs and traps focus until explicitly discarded', async ({ page }) => {
  await sample(page)
  await page.getByRole('button', { name: 'Add expense', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'Add expense', exact: true })
  await form.getByLabel('Expense name', { exact: true }).fill('Do not lose this fuel')
  await form.getByLabel('Amount paid or valued (₱)', { exact: false }).fill('87.25')
  await page.keyboard.press('Escape')
  const confirmation = discardDialog(page)
  await expect(confirmation).toBeVisible()
  await expect(confirmation.getByRole('button', { name: 'Keep editing', exact: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(confirmation.getByRole('button', { name: 'Discard changes', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(confirmation.getByRole('button', { name: 'Keep editing', exact: true })).toBeFocused()
  await confirmation.getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(confirmation).toHaveCount(0)
  await expect(form.getByLabel('Expense name', { exact: true })).toHaveValue('Do not lose this fuel')
  await expect(form.getByLabel('Amount paid or valued (₱)', { exact: false })).toHaveValue('87.25')
  await form.getByRole('button', { name: 'Close / Isara', exact: true }).click()
  await confirmation.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
  await expect(page.getByRole('button', { name: 'Edit Do not lose this fuel', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Add expense', exact: true }).click()
  await expect(form.getByLabel('Expense name', { exact: true })).toHaveValue('')
  await form.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

