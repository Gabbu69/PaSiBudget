test('200 percent equivalent reflow retains access to forms and mobile navigation', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 1050 })
  await sample(page)
  // Browser zoom reduces the layout viewport. Half the width and height of
  // 1440x1050 exercises 200% reflow without relying on browser chrome shortcuts.
  await page.setViewportSize({ width: 720, height: 525 })
  await nav(page, 'Expenses')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
  await page.getByRole('button', { name: 'Add expense', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'Add expense', exact: true })
  await form.getByLabel('Expense name', { exact: true }).fill('Zoom keyboard entry')
  await form.getByRole('button', { name: 'Save expense', exact: true }).click()
  await expect(form).toHaveCount(0)
  await expect(page.getByRole('row').filter({ hasText: 'Zoom keyboard entry' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('zoom-200-percent.png'), fullPage: true })
})
